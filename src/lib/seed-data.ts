export type SeedTask = {
  number: number;
  slug: string;
  title: string;
  week: number;
  weekTitle: string;
  tool: string;
  description: string;
  example?: string;
  dateLabel: string;
  publishAt: string;
  closesAt: string;
  manualState: "auto" | "open" | "closed";
  points: number;
  fields: SeedField[];
};

// Приём ответов закрывается в 00:00 МСК после 25 декабря (26.12 00:00 MSK).
const CLOSES_AT = "2026-12-26T00:00:00+03:00";

const WEEK_TITLES: Record<number, string> = {
  1: "Неделя 1. Загадываем желания и ищем причины",
  2: "Неделя 2. Подводим итоги и автоматизируем хлопоты",
  3: "Неделя 3. Ищем баги, выбираем подарки и книги",
  4: "Неделя 4. Строим планы и благодарим друг друга",
};

function task(
  number: number,
  slug: string,
  title: string,
  week: number,
  tool: string,
  dateLabel: string,
  publishDate: string,
  description: string,
  fields: SeedField[],
  extra: Partial<SeedTask> = {},
): SeedTask {
  return {
    number,
    slug,
    title,
    week,
    weekTitle: WEEK_TITLES[week],
    tool,
    dateLabel,
    // Открытие задания — по календарю, ровно в 00:00 по московскому времени.
    publishAt: `${publishDate}T00:00:00+03:00`,
    closesAt: CLOSES_AT,
    manualState: "auto",
    points: 10,
    description: description.trim(),
    fields,
    ...extra,
  };
}

